/** 레벨 목록 — 데이터에서 자동 도출 (레벨 확정 시 순서 지정이 필요하면 상수 배열로 교체). */
export const GRAMMAR_LEVELS: string[] = [...new Set(GRAMMAR_CURRICULA.map((c) => c.레벨))];

export function countSubunitTopics(sub: GrammarSubunit): number {
  const flat = sub.학습주제?.length ?? 0;
  const grouped = (sub.학습주제그룹 ?? []).reduce((s, g) => s + g.주제.length, 0);
  return flat + grouped;
}

/** 대단원 하나의 주제 수 (직속 학습주제 + 중단원 트리 합산). */
export function countBigunitTopics(big: GrammarBigunit): number {
  const direct = big.학습주제?.length ?? 0;
  const nested = (big.중단원 ?? []).reduce((t, mid) => t + mid.소단원.reduce((u, sub) => u + countSubunitTopics(sub), 0), 0);
  return direct + nested;
}

export function countTopics(cur: GrammarCurriculum): number {
  return cur.대단원.reduce((s, big) => s + countBigunitTopics(big), 0);
}
