/**
 * VIP 영어 '문법 문제관리' 진도(문법 커리큘럼) 데이터. 수학 문제관리(math-curriculum)와 동일 구조.
 * - 과정(레벨) > 대단원 > 중단원 > 소단원 > 학습주제[] (필요 시 학습주제그룹으로 1단계 더)
 * - 문제 생성은 추후 학습주제(topicKey) 기준으로 연결.
 *
 * 중등 LEVEL 1~3 = 교재 목차 기준 (챕터·유닛 번호는 표시에서 제외, 제목만 사용).
 * 분량이 커지면 수학 중등처럼 lib/grammar-curriculum-data/*.json 으로 분리.
 */

/** 소단원 아래의 주제 묶음 (그룹명 + 주제 목록) — 목차가 깊은 레벨에서 사용. */
export interface GrammarTopicGroup {
  그룹명: string;
  주제: string[];
}
export interface GrammarSubunit {
  소단원명: string;
  /** 소단원 바로 아래 주제 목록. */
  학습주제?: string[];
  /** 소단원 > 그룹 > 주제 — 학습주제 대신 이 필드를 채운다. */
  학습주제그룹?: GrammarTopicGroup[];
}
export interface GrammarMidunit {
  중단원명: string;
  소단원: GrammarSubunit[];
}
export interface GrammarBigunit {
  대단원명: string;
  /** 목차가 깊은 교재용 — 대단원 > 중단원 > 소단원 > 주제. */
  중단원?: GrammarMidunit[];
  /** 목차가 얕은 교재용(챕터>유닛 2단) — 대단원 바로 아래 주제. LEVEL 1 이 이 형태. */
  학습주제?: string[];
}

export interface GrammarCurriculum {
  과정: string;
  /** 레벨 — 과정 셀렉터를 optgroup 으로 나누는 기준 (예: 중등 / 고등 / Level 1…). */
  레벨: string;
  대단원: GrammarBigunit[];
}

/**
 * 학습주제 1개를 가리키는 안정 키 (문제 저장·조회용). 경로 세그먼트를 ' > ' 로 이어 사용.
 * (과정, 대단원, 중단원, 소단원, [그룹명], 주제)
 */
export function grammarTopicKey(...parts: string[]): string {
  return parts.filter(Boolean).join(' > ');
}

