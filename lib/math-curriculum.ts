/** 중등 소단원 아래의 주제 묶음 (그룹명 + 주제 목록). */
export interface MathTopicGroup {
  그룹명: string;
  주제: string[];
}
export interface MathSubunit {
  소단원명: string;
  /** 고등: 소단원 바로 아래 주제 목록. */
  학습주제?: string[];
  /** 중등: 소단원 > 그룹 > 주제. 학습주제 대신 이 필드를 채운다. */
  학습주제그룹?: MathTopicGroup[];
}
export interface MathMidunit {
  중단원명: string;
  소단원: MathSubunit[];
}
export interface MathBigunit {
  대단원명: string;
  중단원: MathMidunit[];
}
/** 학교급 — 교과 셀렉터를 고등/중등 그룹(optgroup)으로 나누는 기준. */
export type SchoolLevel = '고등' | '중등';
export const SCHOOL_LEVELS: SchoolLevel[] = ['고등', '중등'];

export interface MathCurriculum {
  교과: string;
  학교급: SchoolLevel;
  대단원: MathBigunit[];
}

/**
 * 학습주제 1개를 가리키는 안정 키 (문제 저장·조회용). 경로 세그먼트를 ' > ' 로 이어 사용.
 * 고등: (교과, 대단원, 중단원, 소단원, 주제) / 중등: (교과, 대단원, 중단원, 소단원, 그룹명, 주제)
 */
export function mathTopicKey(...parts: string[]): string {
  return parts.filter(Boolean).join(' > ');
}

